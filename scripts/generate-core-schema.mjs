function fkSql([table, column, targetTable, targetColumn, onDelete, constraint]) {
  return `do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.${table}'::regclass
      and conname = '${constraint}'
  ) then
    alter table public.${identifier(table)}
      add constraint ${identifier(constraint)}
      foreign key (${identifier(column)})
      references public.${identifier(targetTable)} (${identifier(targetColumn)})
      on delete ${onDelete};
  end if;
end $$;`;
}

