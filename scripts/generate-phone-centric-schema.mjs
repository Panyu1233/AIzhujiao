const triggerSql = `
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists user_info_mini_set_updated_at on public.user_info_mini;
create trigger user_info_mini_set_updated_at
before update on public.user_info_mini
for each row execute function public.set_updated_at();

drop trigger if exists user_info_agent_set_updated_at on public.user_info_agent;
create trigger user_info_agent_set_updated_at
before update on public.user_info_agent
for each row execute function public.set_updated_at();

drop trigger if exists user_info_set_updated_at on public.user_info;
create trigger user_info_set_updated_at
before update on public.user_info
for each row execute function public.set_updated_at();
`;

const securitySql = `
-- 仅后端 secret/service_role 可访问；浏览器端 publishable key 默认读不到业务数据
alter table public.user_info_mini enable row level security;
alter table public.user_info_agent enable row level security;
alter table public.user_info enable row level security;
alter table public.chat_message enable row level security;

grant usage on schema public to service_role;
grant all privileges on public.user_info_mini, public.user_info_agent, public.user_info, public.chat_message
  to service_role;
grant all privileges on all sequences in schema public to service_role;
`;

