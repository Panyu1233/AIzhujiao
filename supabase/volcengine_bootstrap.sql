-- 跨表关联：聊天记录与校准结果都允许先落数据、后补主用户。
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.ai_teacher_chat_message'::regclass
      and conname = 'ai_teacher_chat_message_user_id_fk'
  ) then
    alter table public.ai_teacher_chat_message
      add constraint ai_teacher_chat_message_user_id_fk
      foreign key (user_id) references public.ai_teacher_user_info(id)
      on delete set null;
  end if;
end $$;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.ai_teacher_user_info'::regclass
      and conname = 'ai_teacher_user_info_merge_to_user_id_fk'
  ) then
    alter table public.ai_teacher_user_info
      add constraint ai_teacher_user_info_merge_to_user_id_fk
      foreign key (merge_to_user_id) references public.ai_teacher_user_info(id)
      on delete set null;
  end if;
end $$;

create or replace function public.ai_teacher_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

