const identifier = (name) => {
  if (!/^[a-z_][a-z0-9_]*$/.test(name)) throw new Error(`Unsafe identifier: ${name}`);
  return `"${name}"`;
};

function mapType(type) {
  const value = String(type || '').trim().toUpperCase();
  if (value === 'BIGINT') return 'bigint';
  if (value === 'INT') return 'integer';
  if (value === 'TINYINT') return 'smallint';
  if (value === 'TEXT') return 'text';
  if (value === 'JSON') return 'jsonb';
  if (value === 'BOOLEAN') return 'boolean';
  if (value === 'DATE') return 'date';
  if (value === 'DATETIME') return 'timestamptz';
  const varchar = value.match(/^VARCHAR\((\d+)\)$/);
  if (varchar) return `varchar(${varchar[1]})`;
  const decimal = value.match(/^DECIMAL\((\d+),(\d+)\)$/);
  if (decimal) return `numeric(${decimal[1]},${decimal[2]})`;
  throw new Error(`Unsupported type: ${type}`);
}

function defaultValue(name) {
  if (name === 'created_at' || name === 'updated_at') return ' default now()';
  if (name === 'status') return ' default 1';
  if (name === 'privacy_consent' || name === 'hit_count' || name === 'priority') return ' default 0';
  if (name === 'version') return ' default 1';
  if (['is_ai_reply', 'is_sensitive', 'memory_candidate', 'is_deleted'].includes(name)) return ' default 0';
  return '';
}

function columnSql(table, column) {
  const name = identifier(column.name);
  const type = mapType(column.type);
  if ((column.key || '').includes('PK')) {
    return `${name} ${type} generated by default as identity primary key`;
  }
  const forceRequired = column.name === 'phone' || (table === 'chat_message' && column.name === 'phone_snapshot');
  const notNull = column.required === 'Y' || forceRequired ? ' not null' : '';
  const check = column.name === 'phone' || column.name === 'phone_snapshot'
    ? ` check (btrim(${name}) <> '')`
    : '';
  return `${name} ${type}${defaultValue(column.name)}${notNull}${check}`;
}

function createTableSql(table) {
  return `create table if not exists public.${identifier(table.table)} (\n  ${table.columns
    .map((column) => columnSql(table.table, column))
    .join(',\n  ')}\n);`;
}

function uniqueIndexSql(table, column) {
  return `create unique index if not exists ${identifier(`${table}_${column}_uk`)}\n  on public.${identifier(table)} (${identifier(column)});`;
}

function indexSql(table, column, type) {
  const indexName = identifier(`${table}_${column}_idx`);
  const tableName = `public.${identifier(table)}`;
  const field = identifier(column);
  const normalizedType = String(type || '').toUpperCase();
  if (normalizedType === 'JSON') {
    return `create index if not exists ${indexName}\n  on ${tableName} using gin (${field} jsonb_path_ops);`;
  }
  const varchar = normalizedType.match(/^VARCHAR\((\d+)\)$/);
  if (varchar && Number(varchar[1]) > 255) {
    return `create index if not exists ${indexName}\n  on ${tableName} using hash (${field});`;
  }
  return `create index if not exists ${indexName}\n  on ${tableName} (${field});`;
}

function generateIndexes(table) {
  const result = [];
  for (const column of table.columns) {
    const key = String(column.key || '');
    if (key.includes('UK')) result.push(uniqueIndexSql(table.table, column.name));
    if (key.includes('IDX')) result.push(indexSql(table.table, column.name, column.type));
  }
  return result;
}

