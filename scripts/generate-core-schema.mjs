const identifier = (name) => {
  if (!/^[a-z_][a-z0-9_]*$/.test(name)) throw new Error(`Unsafe identifier: ${name}`);
  return `"${name}"`;
};

function mapType(type) {
  const value = String(type || '').trim().toUpperCase();
  if (/^BIGINT$/.test(value)) return 'bigint';
  if (/^INT$/.test(value)) return 'integer';
  if (/^TINYINT$/.test(value)) return 'smallint';
  if (/^TEXT$/.test(value)) return 'text';
  if (/^JSON$/.test(value)) return 'jsonb';
  if (/^BOOLEAN$/.test(value)) return 'boolean';
  if (/^DATE$/.test(value)) return 'date';
  if (/^DATETIME$/.test(value)) return 'timestamptz';
  const varchar = value.match(/^VARCHAR\((\d+)\)$/);
  if (varchar) return `varchar(${varchar[1]})`;
  const decimal = value.match(/^DECIMAL\((\d+),(\d+)\)$/);
  if (decimal) return `numeric(${decimal[1]},${decimal[2]})`;
  throw new Error(`Unsupported column type: ${type}`);
}

function defaultValue(table, column) {
  if (column.name === 'created_at' || column.name === 'updated_at') return ' default now()';
  if (column.name === 'status') return ' default 1';
  if (column.name === 'privacy_consent' || column.name === 'hit_count' || column.name === 'priority') return ' default 0';
  if (column.name === 'version') return ' default 1';
  if (column.name === 'is_ai_reply' || column.name === 'is_sensitive' || column.name === 'memory_candidate' || column.name === 'is_deleted') return ' default 0';
  return '';
}

function columnSql(table, column) {
  const name = identifier(column.name);
  const type = mapType(column.type);
  if ((column.key || '').includes('PK')) {
    return `${name} ${type} generated by default as identity primary key`;
  }
  const notNull = column.required === 'Y' ? ' not null' : '';
  return `${name} ${type}${defaultValue(table, column)}${notNull}`;
}

function uniqueIndexSql(table, column) {
  return `create unique index if not exists ${identifier(`${table}_${column.name}_uk`)}\n  on public.${identifier(table)} (${identifier(column.name)});`;
}

function indexSql(table, column) {
  const indexName = identifier(`${table}_${column.name}_idx`);
  const tableName = `public.${identifier(table)}`;
  const field = identifier(column.name);
  const type = String(column.type || '').toUpperCase();
  if (type === 'JSON') {
    return `create index if not exists ${indexName}\n  on ${tableName} using gin (${field} jsonb_path_ops);`;
  }
  const varchar = type.match(/^VARCHAR\((\d+)\)$/);
  if (varchar && Number(varchar[1]) > 255) {
    return `create index if not exists ${indexName}\n  on ${tableName} using hash (${field});`;
  }
  return `create index if not exists ${indexName}\n  on ${tableName} (${field});`;
}

const fourTableSql = definitions.map((table) => {
  const cols = table.columns.map((column) => columnSql(table.table, column)).join(',\n  ');
  const indexes = [];
  for (const column of table.columns) {
    const key = String(column.key || '');
    if (key.includes('UK')) indexes.push(uniqueIndexSql(table.table, column));
    if (key.includes('IDX')) indexes.push(indexSql(table.table, column));
  }
  return [
    `-- ${table.sheet}`,
    `create table if not exists public.${identifier(table.table)} (`,
    `  ${cols}`,
    ');',
    ...indexes,
  ].join('\n');
}).join('\n\n');

